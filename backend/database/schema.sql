create table if not exists public.girodegaragem_artigos (
    id bigint generated by default as identity primary key,
    titulo varchar(200) not null check (trim(titulo) <> ''),
    descricao varchar(300),
    categoria varchar(50) not null check (trim(categoria) <> ''),
    conteudo text not null check (trim(conteudo) <> ''),
    data_publicacao date not null default current_date
);

alter table public.girodegaragem_artigos enable row level security;
